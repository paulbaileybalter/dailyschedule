#!/usr/bin/env python3
"""
Turns PB_Daily_Schedule.xlsx into:
  src/defaults.js            default weekly routine + ongoing projects (from the "Master" tab)
  public/data/history.json   every past "WC dd.mm.yy" week, ready for the one-time import button

Run again any time:  python3 tools/build-from-spreadsheet.py path/to/PB_Daily_Schedule.xlsx
Needs: pip install openpyxl
"""
import datetime as dt, json, re, sys, pathlib
import openpyxl

xlsx = sys.argv[1] if len(sys.argv) > 1 else 'PB_Daily_Schedule.xlsx'
root = pathlib.Path(__file__).resolve().parent.parent
CURRENT_MONDAY = dt.date(2026, 11, 2)   # the week in progress: Monday imported as done, Tue-Fri left open

FIXES = [(r'\bRecieve\b', 'Receive'), (r'\bConverstation\b', 'Conversation'), (r'\bCreat\b', 'Create'),
         (r'\bStockake\b', 'Stocktake'), (r'\bManufcaturing\b', 'Manufacturing'), (r'\bNirtogen\b', 'Nitrogen'),
         (r'\binvioces\b', 'invoices'), (r'\bregardin\b', 'regarding'), (r'\bodering\b', 'ordering'), (r'\bNote:\s*', '')]
def norm(s):
    s = re.sub(r'\s+', ' ', str(s)).strip()
    for a, b in FIXES: s = re.sub(a, b, s)
    return s

def split_time(t):
    """'1330 Meeting' -> ('13:30','Meeting'); mirrors parseTime() in public/ops.js"""
    m = re.match(r'^([01]\d|2[0-3])([0-5]\d)\s+(.+)$', t)
    if m: return f'{m[1]}:{m[2]}', m[3].strip()
    m = re.match(r'^(\d{1,2}):(\d{2})\s*[-:]?\s*(.+)$', t)
    if m and int(m[1]) < 24 and int(m[2]) < 60: return f'{int(m[1]):02d}:{m[2]}', m[3].strip()
    m = re.match(r'^(\d{1,2})\s*(am|pm)\s+(.+)$', t, re.I)
    if m:
        h = int(m[1]) % 12 + (12 if m[2].lower() == 'pm' else 0)
        return f'{h:02d}:00', m[3].strip()
    return '', t

def b36(n):
    d = '0123456789abcdefghijklmnopqrstuvwxyz'; out = ''
    while n: n, r = divmod(n, 36); out = d[r] + out
    return out or '0'

wb = openpyxl.load_workbook(xlsx)

# ---------- Master -> defaults ----------
ws = wb['Master']
routine = {str(i): [] for i in range(1, 6)}
for col in range(1, 6):
    seen = set()
    for r in range(3, ws.max_row + 1):
        v = ws.cell(r, col).value
        if not isinstance(v, str) or not v.strip() or v.strip() in ('-', 'Potential Checks'): continue
        t = norm(v)
        if t in seen: continue
        seen.add(t)
        tm, tx = split_time(t)
        item = {'id': f'm{col}-{len(routine[str(col)]) + 1:02d}', 'text': tx}
        if tm: item['time'] = tm
        routine[str(col)].append(item)
projects = []
for r in range(2, ws.max_row + 1):
    v = ws.cell(r, 6).value
    if isinstance(v, str) and v.strip():
        projects.append({'id': f'p{len(projects) + 1:02d}', 'text': norm(v), 'done': False})
(root / 'src' / 'defaults.js').write_text(
    '// Generated by tools/build-from-spreadsheet.py from the "Master" tab. Used until you save your own routine in the app.\n'
    'export const DEFAULT_ROUTINE = {\n' + ',\n'.join(f' "{k}": [\n' + ',\n'.join('  ' + json.dumps(i, ensure_ascii=False) for i in v) + '\n ]' for k, v in routine.items()) + '\n};\n'
    'export const DEFAULT_PROJECTS = [\n' + ',\n'.join(' ' + json.dumps(i, ensure_ascii=False) for i in projects) + '\n];\n')

# ---------- Weekly tabs -> history ----------
def sheet_monday(name, ws):
    s = name.replace('WC', '').strip()
    cands = []
    if '.' in s:
        d, m, y = s.split('.'); cands = [dt.date(2000 + int(y), int(m), int(d))]
    else:
        y = int(s[-2:]); rest = s[:-2]
        for k in (1, 2):
            if len(rest) - k >= 1:
                try: cands.append(dt.date(2000 + y, int(rest[len(rest) - k:]), int(rest[:len(rest) - k])))
                except ValueError: pass
    mondays = [c for c in cands if c.weekday() == 0]
    if mondays: return mondays[0]
    # e.g. a tab named for the Tuesday after Easter Monday: snap to that week's Monday
    return cands[0] - dt.timedelta(days=cands[0].weekday()) if cands else None

NOTE_DAY = re.compile(r'^(kings birthday|annual leave|public holiday|sick leave|working from home|work from home)\b', re.I)
SKIP = re.compile(r'not\s*necessary', re.I)
SKIP_ROW = re.compile(r'^(every day|last|next|-)$', re.I)
weeks, report = {}, []
for ws in wb.worksheets:
    if ws.title == 'Master': continue
    mon = sheet_monday(ws.title, ws)
    if not mon:
        report.append(f'!! could not date sheet {ws.title!r}'); continue
    days, n = {}, 0
    for col in range(1, 6):
        date = mon + dt.timedelta(days=col - 1)
        iso = date.isoformat()
        tasks, notes, seen = [], [], 0
        for r in range(3, ws.max_row + 1):
            v = ws.cell(r, col).value
            if not isinstance(v, str) or not v.strip() or SKIP_ROW.match(v.strip()): continue
            t = norm(v)
            if NOTE_DAY.match(t): notes.append(t); continue
            seen += 1
            is_past = mon < CURRENT_MONDAY or (mon == CURRENT_MONDAY and col == 1)
            skip = bool(SKIP.search(t))
            tm, tx = split_time(t)
            tasks.append({'id': f'h{b36(int(date.strftime("%Y%m%d")))}{seen:02d}', 'text': tx,
                          'done': is_past and not skip, 'skip': is_past and skip, 'doneAt': None, 'time': tm, 'cat': '', 'src': '', 'note': ''})
        if tasks or notes:
            days[iso] = {'tasks': tasks, 'note': '; '.join(notes), 'seeded': True}
            n += len(tasks)
    if days:
        weeks[mon.isoformat()] = {'days': days}
    report.append(f'{ws.title:14} -> week of {mon}  {n} tasks')
out = root / 'public' / 'data' / 'history.json'
out.write_text(json.dumps({'weeks': dict(sorted(weeks.items()))}, ensure_ascii=False, separators=(',', ':')))
print('\n'.join(report))
print(f'\nroutine: ' + ', '.join(f'{k}:{len(v)}' for k, v in routine.items()) + f' | projects: {len(projects)} | weeks: {len(weeks)} | {out.stat().st_size // 1024} KB')
